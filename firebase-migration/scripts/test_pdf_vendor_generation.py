"""Generated-source publication does not follow old destination links."""
import importlib.util
from pathlib import Path
import tempfile
import unittest
import os
spec=importlib.util.spec_from_file_location('vendor_pdf',Path(__file__).with_name('vendor-pdf-text-assets.py'))
vendor=importlib.util.module_from_spec(spec);spec.loader.exec_module(vendor)
class PdfVendorPublicationTests(unittest.TestCase):
    def test_replacement_does_not_mutate_a_hardlink_target(self):
        with tempfile.TemporaryDirectory(prefix='aurora-pdf-generator-') as temp:
            root=Path(temp);original=root/'kept.txt';original.write_bytes(b'keep independent target')
            target=root/'document_pdf_api.mjs';os.link(original,target)
            vendor.publish(target,b'new generated bytes')
            self.assertEqual(original.read_bytes(),b'keep independent target');self.assertEqual(target.read_bytes(),b'new generated bytes')
            self.assertEqual(target.stat().st_nlink,1)
    def test_plain_replacement_leaves_no_staging_directory(self):
        with tempfile.TemporaryDirectory(prefix='aurora-pdf-generator-') as temp:
            root=Path(temp);target=root/'document_pdf_vendor.json';vendor.publish(target,b'one');vendor.publish(target,b'two')
            self.assertEqual(target.read_bytes(),b'two');self.assertEqual(list(root.iterdir()),[target])
if __name__=='__main__':unittest.main()
