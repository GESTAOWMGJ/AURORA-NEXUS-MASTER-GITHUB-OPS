import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, writeFile, readFile, readdir, link, symlink, mkdir, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {atomicGeneratedFile} from './atomic-generated-file.mjs';

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'aurora-atomic-generated-test-'));
  t.after(() => rm(root, {recursive: true, force: true}));
  return root;
}
test('creates and replaces generated bytes with no staging residue', async t => {
  const root = await fixture(t), name = 'document_intake_core.cjs';
  await atomicGeneratedFile(root, name, Buffer.from('first'));
  await atomicGeneratedFile(root, name, Buffer.from('second'));
  assert.equal(await readFile(join(root, name), 'utf8'), 'second');
  assert.deepEqual(await readdir(root), [name]);
});
test('hardlinked destination does not overwrite the other link', async t => {
  const root = await fixture(t), name = 'document_fact_mapping.cjs';
  await writeFile(join(root, 'outside'), 'preserved');
  await link(join(root, 'outside'), join(root, name));
  await atomicGeneratedFile(root, name, Buffer.from('generated'));
  assert.equal(await readFile(join(root, 'outside'), 'utf8'), 'preserved');
  assert.equal(await readFile(join(root, name), 'utf8'), 'generated');
});
test('symbolic destination is replaced without following it', async t => {
  const root = await fixture(t), name = 'document-intake-manifest.json';
  await writeFile(join(root, 'outside'), 'preserved');
  try { await symlink(join(root, 'outside'), join(root, name), 'file'); }
  catch (error) { if (['EPERM', 'EACCES'].includes(error.code)) { t.skip('Symbolic-link creation not authorized'); return; } throw error; }
  await atomicGeneratedFile(root, name, Buffer.from('{}'));
  assert.equal(await readFile(join(root, 'outside'), 'utf8'), 'preserved');
  assert.equal(await readFile(join(root, name), 'utf8'), '{}');
});
test('invalid target and failed rename preserve existing content', async t => {
  const root = await fixture(t), name = 'document_intake_core.cjs';
  await assert.rejects(atomicGeneratedFile(root, '../outside', Buffer.from('x')), /PATH_REJECTED/);
  await mkdir(join(root, name));
  await writeFile(join(root, name, 'sentinel'), 'preserved');
  await assert.rejects(atomicGeneratedFile(root, name, Buffer.from('x')));
  assert.equal(await readFile(join(root, name, 'sentinel'), 'utf8'), 'preserved');
  assert.deepEqual(await readdir(root), [name]);
});
